// Package windowsprotection describes immutable protection ownership records.
// Decoding a record does not prove a process, file, rule or firewall owner. A
// Windows adapter must independently retain and compare those native objects
// before using this identity; schema-1 rollback files are never adopted here.
package windowsprotection

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"strconv"
	"strings"
)

const (
	OwnerRecordSchema = 2
	OwnerRecordKind   = "routervpn-owned-legacy-protection"
	OwnerRecordLimit  = 4096
)

// Capture is the connection identity captured before a protection transition.
// Generation belongs to that operation, not the currently selected profile.
type Capture struct {
	SessionID    string `json:"session_id"`
	SourceSHA256 string `json:"source_sha256"`
	ConfigSHA256 string `json:"config_sha256"`
	NetworkID    string `json:"network_id"`
	Generation   uint64 `json:"generation"`
}

// Controller is comparison data; a parsed caller value is never a request to
// open or signal its PID. Native restart recovery may query a value captured
// from its protected, locked journal, retaining only read/synchronize handles.
// Its constructor reads all fields from an independently retained process.
// StartTimeUTCTicks is an identity component, not a freshness assertion.
type Controller struct {
	PID               uint32 `json:"pid"`
	StartTimeUTCTicks int64  `json:"start_time_utc_ticks"`
	SID               string `json:"sid"`
	AuthenticationID  uint64 `json:"authentication_id"`
	SessionID         uint32 `json:"session_id"`
}

// OwnerRecord is immutable. Rule/profile mutation journals are a separate
// contract: this record grants no firewall authority or recovery permission.
// OwnerID must be generated by the native creator, not selected by a reader.
type OwnerRecord struct {
	Schema     int        `json:"schema"`
	Kind       string     `json:"kind"`
	OwnerID    string     `json:"owner_id"`
	Capture    Capture    `json:"capture"`
	Controller Controller `json:"controller"`
	Policy     string     `json:"policy"`
}

func (c Capture) Validate() error {
	if !lowerHex(c.SessionID, 32) || !lowerHex(c.SourceSHA256, 64) ||
		!lowerHex(c.ConfigSHA256, 64) || !lowerHex(c.NetworkID, 32) || c.Generation == 0 {
		return errors.New("Windows protection capture has no exact bounded connection identity")
	}
	return nil
}

func (c Controller) Validate() error {
	// This is the upper bound of DateTime.UtcTicks, matching retained Windows
	// process creation readback. No age or liveness is inferred from the value.
	if c.PID == 0 || c.StartTimeUTCTicks <= 0 || c.StartTimeUTCTicks > 3155378975999999999 ||
		c.AuthenticationID == 0 || !validSID(c.SID) {
		return errors.New("Windows protection controller has no bounded process creation and token identity")
	}
	return nil
}

func (r OwnerRecord) Validate() error {
	if r.Schema != OwnerRecordSchema || r.Kind != OwnerRecordKind || !lowerHex(r.OwnerID, 32) ||
		(r.Policy != "on-connect" && r.Policy != "always") {
		return errors.New("Windows protection requires its exact schema-2 owner record and policy")
	}
	if err := r.Capture.Validate(); err != nil {
		return err
	}
	return r.Controller.Validate()
}

// CanonicalOwnerRecord emits compact JSON in the declared field order without
// a trailing newline. Callers must not append or normalize bytes after capture.
func CanonicalOwnerRecord(record OwnerRecord) ([]byte, error) {
	if err := record.Validate(); err != nil {
		return nil, err
	}
	body, err := json.Marshal(record)
	if err != nil || len(body) == 0 || len(body) > OwnerRecordLimit {
		return nil, errors.New("Windows protection owner encoding exceeds its bound")
	}
	return body, nil
}

// ParseOwnerRecord accepts only the exact canonical encoding. Re-encoding
// equality rejects duplicate, missing, case-aliased or escaped field names,
// null/coerced fields, whitespace aliases and noncanonical numeric encodings,
// including missing fields whose numeric zero is otherwise structurally valid.
func ParseOwnerRecord(raw []byte) (OwnerRecord, error) {
	var record OwnerRecord
	if len(raw) == 0 || len(raw) > OwnerRecordLimit {
		return record, errors.New("Windows protection owner input is empty or unbounded")
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&record); err != nil {
		return OwnerRecord{}, errors.New("Windows protection owner input has unsupported fields or types")
	}
	var extra any
	if decoder.Decode(&extra) != io.EOF {
		return OwnerRecord{}, errors.New("Windows protection owner input has trailing content")
	}
	canonical, err := CanonicalOwnerRecord(record)
	if err != nil {
		return OwnerRecord{}, err
	}
	if !bytes.Equal(raw, canonical) {
		return OwnerRecord{}, errors.New("Windows protection owner input is not its exact canonical encoding")
	}
	return record, nil
}

// OwnerRecordSHA256 binds the exact validated bytes. A digest does not replace
// the independent native process/file/rule ownership proof required by users.
func OwnerRecordSHA256(raw []byte) (string, error) {
	if _, err := ParseOwnerRecord(raw); err != nil {
		return "", err
	}
	digest := sha256.Sum256(raw)
	return hex.EncodeToString(digest[:]), nil
}

func lowerHex(value string, length int) bool {
	if len(value) != length {
		return false
	}
	for _, digit := range value {
		if digit < '0' || digit > '9' && digit < 'a' || digit > 'f' {
			return false
		}
	}
	return true
}

func decimal(value string, bits int) (uint64, bool) {
	if value == "" || len(value) > 10 || len(value) > 1 && value[0] == '0' {
		return 0, false
	}
	for _, digit := range value {
		if digit < '0' || digit > '9' {
			return 0, false
		}
	}
	number, err := strconv.ParseUint(value, 10, bits)
	return number, err == nil
}

func validSID(value string) bool {
	if len(value) > 184 || !strings.HasPrefix(value, "S-1-") {
		return false
	}
	parts := strings.Split(value[4:], "-")
	if len(parts) < 2 || len(parts) > 16 {
		return false
	}
	// MS-DTYP 2.4.2.1: decimal authority below 2^32, otherwise 0x plus
	// twelve hexadecimal digits; one to fifteen decimal DWORD subauthorities.
	// https://learn.microsoft.com/openspecs/windows_protocols/ms-dtyp/c92a27b1-c772-4fa7-a432-15df5f1b66a1
	if strings.HasPrefix(parts[0], "0x") {
		if len(parts[0]) != 14 {
			return false
		}
		for _, digit := range parts[0][2:] {
			if !(digit >= '0' && digit <= '9' || digit >= 'a' && digit <= 'f' || digit >= 'A' && digit <= 'F') {
				return false
			}
		}
		authority, err := strconv.ParseUint(parts[0][2:], 16, 48)
		if err != nil || authority < 1<<32 {
			return false
		}
	} else if _, ok := decimal(parts[0], 32); !ok {
		return false
	}
	for _, part := range parts[1:] {
		if _, ok := decimal(part, 32); !ok {
			return false
		}
	}
	return true
}
