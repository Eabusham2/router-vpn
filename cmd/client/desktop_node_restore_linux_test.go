// Only the already-established native policy/TUN observation is modeled here.
// This fixture exercises real sealed source parsing and retained owner checks;
// it does not claim to create a TUN or grant native activation authority.
func linuxSealedRestoreFixture(t *testing.T, runtimeCover bool) (*linuxSpeedLabPathFixture, common.RouterProfile) {
	t.Helper()
	return linuxSealedRestoreFixtureWithLayer(t, runtimeCover, "")
}

func linuxSealedRestoreFixtureWithLayer(t *testing.T, runtimeCover bool, layer string) (*linuxSpeedLabPathFixture, common.RouterProfile) {
	t.Helper()
	f := newLinuxSpeedLabPathFixture(t)
	profile := cloneRouterProfile(f.a.profiles.Profiles[0])
	profile.StartLayer = layer
	profile.EffectiveMTU = 9000
	profile.DAITAHost, profile.DAITAPort, profile.DAITARateKbps = "10.77.0.1", 45999, 192
	f.a.profiles.Profiles[0] = cloneRouterProfile(profile)
	runtimeProfile := cloneRouterProfile(profile)
	runtimeProfile.DAITAEnabled = runtimeCover
	graph, err := json.Marshal(map[string]any{
		"inbounds": []any{map[string]any{"type": "tun", "tag": "tun-in", "auto_route": true, "strict_route": true}},
		"outbounds": []any{map[string]any{"type": "shadowsocks", "tag": "proxy", "server": profile.Endpoint, "server_port": 8388,
			"method": mobilemultihop.NativeStartLayerMethod, "password": base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{43}, 32))}},
		"route": map[string]any{"final": "proxy"},
	})
	if err != nil {
		t.Fatal(err)
	}
	original, endpoint, err := compileDesktopNode(context.Background(), runtimeProfile, "shadowsocks", map[string][]byte{"sing-box.json": graph}, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	policy, err := mobilemultihop.NewDesktopNodePolicyWithMTU(original, strings.Repeat("b", 32), "linux", 0)
	if err != nil {
		t.Fatal(err)
	}
	source, err := original.LaunchInput()
	if err != nil {
		t.Fatal(err)
	}
	h, meta := f.h, policy.Metadata()
	h.policy, h.source = policy, []byte(source)
	h.launch.mode, h.launch.endpoint, h.launch.root = meta.Mode, endpoint, linuxOwnedControllerRoot
	h.launch.mtuSession, h.launch.configSHA256 = meta.SessionID, meta.ConfigSHA256
	h.selection = linuxprotection.NodeSelection{SessionID: meta.SessionID, SourceSHA256: meta.SourceSHA256,
		ConfigSHA256: meta.ConfigSHA256, Policy: meta.KillSwitchPolicy, HomeLAN: meta.HomeLANAccess}
	h.revision = desktopOwnedNodeProfileToken(profile)
	h.options, h.savedOptions = [3]bool{runtimeCover, false, false}, [3]bool{}
	h.transaction.policy, h.transaction.selection, h.transaction.revision = policy, h.selection, h.revision
	h.transaction.options, h.transaction.savedOptions = h.options, h.savedOptions
	h.ready.SessionID, h.ready.SourceSHA256, h.ready.ConfigSHA256 = meta.SessionID, meta.SourceSHA256, meta.ConfigSHA256
	h.proof.ready = *h.ready
	h.activation.policy, h.activation.selection, h.activation.revision = policy, h.selection, h.revision
	h.activation.options, h.activation.savedOptions, h.activation.proof = h.options, h.savedOptions, *h.proof
	f.a.state.Mode, f.a.state.RuntimeMode, f.a.state.DAITA = meta.Mode, meta.Mode, runtimeCover
	f.live.MTU = 1392
	return f, profile
}

func captureLinuxSealedRestore(t *testing.T, f *linuxSpeedLabPathFixture, profile common.RouterProfile) (*desktopLinuxNodePath, *desktopLinuxNodeRestore) {
	t.Helper()
	path := f.capture(t)
	saved, err := captureDesktopLinuxNodeRestoreWith(context.Background(), f.a, path, profile, f.read)
	if err != nil || saved == nil {
		t.Fatal("could not capture original sealed Linux source", err)
	}
	t.Cleanup(func() { clearDesktopLinuxNodeRestore(saved) })
	return path, saved
}

func TestDesktopLinuxSealedRestoreFreezesSourceOptionsAndLiveMTU(t *testing.T) {
	for _, layer := range []string{"", common.StartLayerAES256GCM, common.StartLayerAES256GCMXOR} {
		for _, cover := range []bool{false, true} {
			t.Run(layer+"/"+map[bool]string{false: "ordinary", true: "separate-runtime-options"}[cover], func(t *testing.T) {
				f, profile := linuxSealedRestoreFixtureWithLayer(t, cover, layer)
				_, saved := captureLinuxSealedRestore(t, f, profile)
				originalConfig, originalSource := f.h.policy.OriginalProfile().Config(), append([]byte(nil), f.h.source...)
				if saved.mtu != 1392 || saved.mtu == profile.EffectiveMTU || saved.options[0] != cover || saved.savedOptions[0] ||
					saved.parent != f.s.parent || saved.session != f.s || saved.journal != f.s.journal || saved.mode != "shadowsocks" {
					t.Fatal("Linux restore lost original owners, separate options or live MTU")
				}
				// Closing the former host or rotating today's generated bytes cannot
				// replace the copied source used to reconstruct the proved execution.
				clear(f.h.source)
				f.h.policy = nil
				compiled, restored, err := saved.compiled(profile)
				if err != nil || compiled.Config() != originalConfig || !bytes.Equal(saved.source, originalSource) ||
					restored.DAITAEnabled != cover || f.a.profiles.Profiles[0].DAITAEnabled || profile.DAITAEnabled {
					t.Fatal("sealed restoration reread mutable inputs or changed saved runtime preferences", err)
				}
				fresh, err := mobilemultihop.NewDesktopNodePolicyWithMTU(compiled, strings.Repeat("d", 32), "linux", saved.mtu)
				if err != nil || fresh.Metadata().SessionID == strings.Repeat("b", 32) || fresh.Metadata().RestoredMTU != 1392 ||
					fresh.OriginalProfile().Config() != originalConfig || fresh.Metadata().StartLayer != layer || restored.StartLayer != layer {
					t.Fatal("fresh restoration substituted the original graph or effective MTU", err)
				}
			})
		}
	}
}

func TestDesktopLinuxSealedRestoreRejectsStaleCapture(t *testing.T) {
	for _, scenario := range []string{"foreign-app", "private-profile", "saved-options", "source", "pending-mtu", "live-lease", "small-mtu", "large-mtu",
		"session", "command", "cancelled", "native-failure", "profile-during-read", "source-during-read", "cancel-during-read"} {
		t.Run(scenario, func(t *testing.T) {
			f, profile := linuxSealedRestoreFixture(t, false)
			path := f.capture(t)
			a := f.a
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			read := f.read
			switch scenario {
			case "foreign-app":
				a = &app{}
			case "private-profile":
				profile.APIToken += "replacement"
			case "saved-options":
				profile.SocksEnabled = true
			case "source":
				f.h.source = bytes.ReplaceAll(f.h.source, []byte("private-token"), []byte("replacement-token"))
			case "pending-mtu":
				f.h.mtu = &desktopLinuxNodeMTUOwner{}
			case "live-lease":
				f.live.Active = true
			case "small-mtu":
				f.live.MTU = 1279
			case "large-mtu":
				f.live.MTU = 9001
			case "session":
				f.s.active = &desktopLinuxNodeHost{}
			case "command":
				f.a.cmd = &exec.Cmd{}
			case "cancelled":
				cancel()
			default:
				read = func(ctx context.Context, h *desktopLinuxNodeHost) (mobilemultihop.DesktopNodeReadyRecord, desktopNodeMTURecord, error) {
					r, m, err := f.read(ctx, h)
					switch scenario {
					case "native-failure":
						err = errors.New("original native read failed")
					case "profile-during-read":
						f.a.profiles.Profiles[0].APIToken += "replacement"
					case "source-during-read":
						f.h.source[0] = '!'
					case "cancel-during-read":
						cancel()
					}
					return r, m, err
				}
			}
			command, before := f.a.cmd, f.a.state
			if saved, err := captureDesktopLinuxNodeRestoreWith(ctx, a, path, profile, read); err == nil || saved != nil {
				t.Fatal("Linux restore captured a foreign, stale or undrained original", err)
			}
			if f.a.cmd != command || f.a.state != before {
				t.Fatal("rejected read-only restore capture changed the current connection")
			}
		})
	}
}

func TestDesktopLinuxSealedRestoreRejectsChangedInputAndExecution(t *testing.T) {
	for _, scenario := range []string{"source", "node", "dns", "options", "start-layer", "mtu", "cleared", "auto", "compare", "server", "mixed", "scope"} {
		t.Run(scenario, func(t *testing.T) {
			f, profile := linuxSealedRestoreFixture(t, false)
			_, saved := captureLinuxSealedRestore(t, f, profile)
			plan := speedLabRestorePlan{profile: profile, linux: saved,
				request: speedLabRequest{Topology: "router", NodeID: profile.ID, Mode: "shadowsocks", Execution: "local"}}
			scope := "speed-lab:restore"
			operation, cancel := context.WithCancel(context.Background())
			defer cancel()
			f.a.cmd, f.a.state.Connected, f.a.connectionContext = nil, false, operation
			if _, _, err := saved.compiled(profile); err != nil {
				t.Fatal("valid original sealed input was not reconstructable", err)
			}
			if err := saved.restartAppCurrent(f.a, operation, profile); err != nil {
				t.Fatal("valid original request failed before the negative control", err)
			}
			expected := "Linux restore lost its exact sealed source, profile or measured MTU"
			switch scenario {
			case "source":
				saved.source[0] = '!'
			case "node":
				plan.profile.APIToken += "replacement"
			case "dns":
				plan.profile.AdGuardIPv4 = "192.168.50.134"
			case "options":
				plan.profile.DAITAEnabled = true
			case "start-layer":
				plan.profile.StartLayer = common.StartLayerAES256GCMXOR
			case "mtu":
				saved.mtu = 9001
			case "cleared":
				clearSpeedLabRestorePlan(plan)
				expected = "Linux restore cannot replay an entered or retired capture"
			case "auto":
				plan.request.Mode = "smart-auto"
				expected = "Linux restore has no single captured proved local execution"
			case "compare", "server":
				plan.request.Execution = scenario
				expected = "Linux restore has no single captured proved local execution"
			case "mixed":
				plan.native = &desktopNodeLaunch{}
				expected = "Linux restore has no single captured proved local execution"
			case "scope":
				scope = "connect"
				expected = "Linux restore has no recognized operation"
			}
			command, before := f.a.cmd, f.a.state
			if err := f.a.restartCapturedDesktopLinuxNode(plan, scope); err == nil || err.Error() != expected || saved.entered || saved.restored != nil {
				t.Fatal("invalid restoration reached native creation or candidate reselection", err)
			}
			if f.a.cmd != command || f.a.state != before {
				t.Fatal("invalid restoration disturbed the original or replacement connection")
			}
		})
	}
}

func TestDesktopLinuxSealedRestorePreflightPreservesReplacement(t *testing.T) {
	for _, scenario := range []string{"original", "command", "connected", "request", "cancel-intent", "cancelled", "profile", "selected-node", "options", "controller", "network"} {
		t.Run(scenario, func(t *testing.T) {
			f, profile := linuxSealedRestoreFixture(t, false)
			_, saved := captureLinuxSealedRestore(t, f, profile)
			operation, cancel := context.WithCancel(context.Background())
			defer cancel()
			f.a.cmd, f.a.state.Connected = nil, false
			f.a.connectionContext = operation
			switch scenario {
			case "command":
				f.a.cmd = &exec.Cmd{}
			case "connected":
				f.a.state.Connected = true
			case "request":
				f.a.connectionContext = context.Background()
			case "cancel-intent":
				f.a.connectionCancelIntent = operation
			case "cancelled":
				cancel()
			case "profile":
				f.a.profiles.Profiles[0].NodeProofID += "replacement"
			case "selected-node":
				f.a.profiles.SelectedID = "replacement"
			case "options":
				f.a.state.DAITA = true
			case "controller":
				f.a.localController = &ownedDesktopController{}
			case "network":
				saved.network += "replacement"
			}
			command, before := f.a.cmd, f.a.state
			err := saved.restartAppCurrent(f.a, operation, profile)
			if (err == nil) != (scenario == "original") || f.a.cmd != command || f.a.state != before {
				t.Fatal("restore preflight accepted or altered a replaced original", err)
			}
		})
	}
}

func TestDesktopLinuxSealedRestoreCleanupOwnsOnlyCopiedSource(t *testing.T) {
	f, profile := linuxSealedRestoreFixture(t, false)
	_, saved := captureLinuxSealedRestore(t, f, profile)
	copyBytes := saved.source
	original := append([]byte(nil), f.h.source...)
	// A fresh host takes a different copy, exactly as source construction does.
	saved.restored = &desktopLinuxNodeHost{source: append([]byte(nil), saved.source...)}
	clearSpeedLabRestorePlan(speedLabRestorePlan{linux: saved})
	clearSpeedLabRestorePlan(speedLabRestorePlan{linux: saved})
	if !saved.cleared || saved.source != nil || !bytes.Equal(copyBytes, make([]byte, len(copyBytes))) ||
		!bytes.Equal(f.h.source, original) || !bytes.Equal(saved.restored.source, original) ||
		!reflect.DeepEqual(f.a.profiles.Profiles[0], profile) {
		t.Fatal("restore-plan cleanup erased another native source or changed the private profile")
	}
}
